// Results of Radar methods that return more than one value. A method that
// returns a single value, such as `Radar.geocode`, returns it directly.
//
// Results only exist for successful requests: a failed request throws a
// [RadarException]. A field is non-nullable when both native SDKs always
// return it on success; if a successful response is missing one anyway, the
// parser throws a [RadarException] with [RadarStatus.errorServer], which is
// what the native SDKs do when they can't parse a response.

/// Returns [value], or throws [RadarException] with
/// [RadarStatus.errorServer] if it is null.
T _require<T>(T? value) =>
    value ?? (throw const RadarException(RadarStatus.errorServer));

/// The result of [Radar.getLocation].
final class RadarLocationResult {
  const RadarLocationResult({required this.location, required this.stopped});

  final RadarLocation location;

  /// Whether the device is stopped.
  final bool stopped;

  @internal
  factory RadarLocationResult.fromMap(ChannelMap map) => RadarLocationResult(
    location: _require(RadarLocation.fromMap(readMap(map['location']))),
    stopped: readBool(map['stopped']) ?? false,
  );
}

/// The result of [Radar.trackOnce].
final class RadarTrackResult {
  const RadarTrackResult({
    required this.location,
    this.events = const [],
    this.user,
  });

  /// The location that was tracked.
  final RadarLocation location;

  /// The events generated by the update. Empty when the update was replayed
  /// as part of a batch of failed updates.
  final List<RadarEvent> events;

  /// The user. Null when the update was replayed as part of a batch of failed
  /// updates.
  final RadarUser? user;

  @internal
  factory RadarTrackResult.fromMap(ChannelMap map) => RadarTrackResult(
    location: _require(RadarLocation.fromMap(readMap(map['location']))),
    events: readList(map['events'], RadarEvent.fromMap),
    user: readObject(map['user'], RadarUser.fromMap),
  );
}

/// The result of the trip methods, such as [Radar.startTrip].
final class RadarTripResult {
  const RadarTripResult({required this.trip, this.events = const []});

  /// The trip after the update. To find a leg updated by
  /// [Radar.updateTripLeg], look it up in [RadarTrip.legs].
  final RadarTrip trip;

  /// The events generated by the update, if any.
  final List<RadarEvent> events;

  @internal
  factory RadarTripResult.fromMap(ChannelMap map) => RadarTripResult(
    trip: _require(readObject(map['trip'], RadarTrip.fromMap)),
    events: readList(map['events'], RadarEvent.fromMap),
  );
}

