/// The type of a [RadarEvent].
enum RadarEventType implements RadarWireEnum {
  /// The native side sent a `user.*` type this version of the plugin does not
  /// recognize.
  unknown('unknown'),

  /// A custom event logged with [Radar.logConversion]. See
  /// [RadarEvent.conversionName].
  conversion('custom'),
  userEnteredGeofence('user.entered_geofence'),
  userExitedGeofence('user.exited_geofence'),
  userDwelledInGeofence('user.dwelled_in_geofence'),
  userEnteredPlace('user.entered_place'),
  userExitedPlace('user.exited_place'),
  userEnteredRegionCountry('user.entered_region_country'),
  userExitedRegionCountry('user.exited_region_country'),
  userEnteredRegionDma('user.entered_region_dma'),
  userExitedRegionDma('user.exited_region_dma'),
  userEnteredRegionState('user.entered_region_state'),
  userExitedRegionState('user.exited_region_state'),
  userEnteredRegionPostalCode('user.entered_region_postal_code'),
  userExitedRegionPostalCode('user.exited_region_postal_code'),
  userNearbyPlaceChain('user.nearby_place_chain'),
  userEnteredBeacon('user.entered_beacon'),
  userExitedBeacon('user.exited_beacon'),
  userStartedTrip('user.started_trip'),
  userUpdatedTrip('user.updated_trip'),
  userStoppedTrip('user.stopped_trip'),
  userApproachingTripDestination('user.approaching_trip_destination'),
  userArrivedAtTripDestination('user.arrived_at_trip_destination'),
  userArrivedAtWrongTripDestination('user.arrived_at_wrong_trip_destination'),
  userFiredTripOrders('user.fired_trip_orders'),
  userFailedFraud('user.failed_fraud'),
  userEnteredHome('user.entered_home'),
  userExitedHome('user.exited_home'),
  userEnteredWork('user.entered_work'),
  userExitedWork('user.exited_work'),
  userStartedTraveling('user.started_traveling'),
  userStoppedTraveling('user.stopped_traveling'),
  userStartedCommuting('user.started_commuting'),
  userStoppedCommuting('user.stopped_commuting');

  const RadarEventType(this.wireValue);

  @override
  @internal
  final String wireValue;

  @internal
  static RadarEventType fromWire(Object? value) {
    if (value is! String) return unknown;
    final type = readEnumOrNull(values, value);
    if (type != null) return type;
    return value.startsWith('user.') ? unknown : conversion;
  }
}

/// Whether an event was verified.
enum RadarEventVerification {
  accept(1),
  unverify(0),
  reject(-1);

  const RadarEventVerification(this.value);

  @internal
  final int value;

  @internal
  static RadarEventVerification? fromWire(Object? value) {
    final number = readInt(value);
    for (final v in values) {
      if (v.value == number) return v;
    }
    return null;
  }
}

/// How confident Radar is in an event.
enum RadarEventConfidence {
  /// Unknown confidence.
  none(0),

  /// Low confidence.
  low(1),

  /// Medium confidence.
  medium(2),

  /// High confidence.
  high(3);

  const RadarEventConfidence(this.value);

  @internal
  final int value;

  @internal
  static RadarEventConfidence fromWire(Object? value) {
    final number = readInt(value);
    for (final v in values) {
      if (v.value == number) return v;
    }
    return none;
  }
}

/// An event generated by Radar, such as a geofence entry.
final class RadarEvent {
  const RadarEvent({
    required this.id,
    required this.type,
    required this.createdAt,
    this.actualCreatedAt,
    this.live = false,
    this.conversionName,
    this.geofence,
    this.place,
    this.region,
    this.beacon,
    this.trip,
    this.fraud,
    this.alternatePlaces = const [],
    this.verifiedPlace,
    this.verification,
    this.confidence = RadarEventConfidence.none,
    this.duration,
    this.location,
    this.replayed = false,
    this.metadata,
  });

  /// The Radar ID of the event.
  final String id;

  /// The type of the event.
  final RadarEventType type;

  /// When the event occurred on the device.
  final DateTime createdAt;

  /// When the event was created on the server. Null for some events, such as
  /// conversions.
  final DateTime? actualCreatedAt;

  /// Whether the event was generated with a live (rather than test)
  /// publishable key.
  final bool live;

  /// For conversion events, the name of the conversion. The native bridges
  /// do not currently send it, so it is only set when the payload carries the
  /// raw conversion type, as the events in a [RadarVerifiedLocationToken] do.
  final String? conversionName;

  /// For geofence events, the geofence.
  final RadarGeofence? geofence;

  /// For place events, the place.
  final RadarPlace? place;

  /// For region events, the region.
  final RadarRegion? region;

  /// For beacon events, the beacon.
  final RadarBeacon? beacon;

  /// For trip events, the trip.
  final RadarTrip? trip;

  /// For fraud events, the fraud checks.
  final RadarFraud? fraud;

  /// For place entry events, alternate place candidates.
  final List<RadarPlace> alternatePlaces;

  /// For accepted place entry events, the verified place.
  final RadarPlace? verifiedPlace;

  /// Whether the event was verified. Null unless the payload came from the
  /// API, as the events in a [RadarVerifiedLocationToken] do.
  final RadarEventVerification? verification;

  /// The confidence level of the event.
  final RadarEventConfidence confidence;

  /// For exit events, how long the user was inside.
  final Duration? duration;

  /// Where the event occurred. Null for events without a location, such as
  /// conversions.
  final RadarLocation? location;

  /// Whether the event was replayed from an offline buffer.
  final bool replayed;

  /// The metadata of the event. Set on conversion events only.
  final Map<String, Object?>? metadata;

  /// Returns null if [map] has no `createdAt`. Both native SDKs always send
  /// one.
  @internal
  static RadarEvent? fromMap(ChannelMap map) {
    final createdAt = readDate(map['createdAt']);
    if (createdAt == null) return null;
    final rawType = readString(map['type']);
    // Android omits `type` for conversion events.
    final type =
        rawType == null
            ? RadarEventType.conversion
            : RadarEventType.fromWire(rawType);
    final conversionName =
        readString(map['conversionName']) ??
        (type == RadarEventType.conversion &&
                rawType != null &&
                rawType != RadarEventType.conversion.wireValue
            ? rawType
            : null);
    return RadarEvent(
      id: readString(map['_id']) ?? '',
      type: type,
      createdAt: createdAt,
      actualCreatedAt: readDate(map['actualCreatedAt']),
      live: readBool(map['live']) ?? false,
      conversionName: conversionName,
      geofence: readObject(map['geofence'], RadarGeofence.fromMap),
      place: readObject(map['place'], RadarPlace.fromMap),
      region: readObject(map['region'], RadarRegion.fromMap),
      beacon: readObject(map['beacon'], RadarBeacon.fromMap),
      trip: readObject(map['trip'], RadarTrip.fromMap),
      fraud: readObject(map['fraud'], RadarFraud.fromMap),
      alternatePlaces: readList(map['alternatePlaces'], RadarPlace.fromMap),
      verifiedPlace: readObject(map['verifiedPlace'], RadarPlace.fromMap),
      verification: RadarEventVerification.fromWire(map['verification']),
      confidence: RadarEventConfidence.fromWire(map['confidence']),
      duration: readMinutes(map['duration']),
      location: _readGeoJsonLocation(map['location'], map['locationAccuracy']),
      replayed: readBool(map['replayed']) ?? false,
      metadata: readJson(map['metadata']),
    );
  }
}

RadarLocation? _readGeoJsonLocation(Object? point, Object? accuracy) {
  final coordinate = RadarCoordinate.fromMap(readMap(point));
  if (coordinate == null) return null;
  return RadarLocation(
    latitude: coordinate.latitude,
    longitude: coordinate.longitude,
    accuracy: readDouble(accuracy),
  );
}
